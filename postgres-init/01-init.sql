-- Создание таблицы posts (если не существует)
CREATE TABLE IF NOT EXISTS posts (
    Id SERIAL PRIMARY KEY,
    Name VARCHAR(30),
    Father VARCHAR(30),
    TextOf VARCHAR(500),
    TypeOf VARCHAR(10),
    Image VARCHAR(100) DEFAULT '',
    Geo VARCHAR(50) DEFAULT ''
);

-- Создание индексов для оптимизации
CREATE INDEX IF NOT EXISTS idx_posts_name ON posts(Name);
CREATE INDEX IF NOT EXISTS idx_posts_father ON posts(Father);

